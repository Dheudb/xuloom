const {_electron:electron}=require('playwright');
const fs=require('node:fs'),path=require('node:path'),os=require('node:os'),assert=require('node:assert/strict');
const {spawn}=require('node:child_process'),readline=require('node:readline');
const root=path.resolve(__dirname,'..'),repo=path.dirname(root);
const fixture=fs.mkdtempSync(path.join(os.tmpdir(),'xuloom-oauth-e2e-'));
const python=process.env.XULOOM_TEST_EXECUTABLE?path.join(path.dirname(process.env.XULOOM_TEST_EXECUTABLE),'resources/python/python.exe'):process.env.XULOOM_PYTHON||'python';
const project=path.join(fixture,'project'),data=path.join(fixture,'data'),config=path.join(fixture,'config'),home=path.join(fixture,'home');
for(const p of [project,data,config,home])fs.mkdirSync(p,{recursive:true});
fs.writeFileSync(path.join(data,'workbench.json'),JSON.stringify({projects:[project],python}));
const env={...process.env,HOME:home,USERPROFILE:home,XULOOM_USER_DATA:data,XULOOM_DATA_DIR:data,XULOOM_CONFIG_DIR:config,XULOOM_SKILLS_PATHS:'',XULOOM_TEST_HEADLESS:'1',XULOOM_CREDENTIAL_STORAGE:'auto'};
for(const name of Object.keys(env))if(name.startsWith('OPENAI_')||name.startsWith('ANTHROPIC_')||['ELECTRON_RUN_AS_NODE','XULOOM_DEV_URL'].includes(name))delete env[name];
async function main(){
 const service=spawn(python,[...(process.env.XULOOM_TEST_EXECUTABLE?['-I']:[]),'-u',path.join(repo,'tests/fixtures/oauth-server.py')],{env,cwd:repo,windowsHide:true,stdio:['pipe','pipe','pipe']});
 let diagnostics='';service.stderr.on('data',b=>diagnostics+=b.toString());
 const lines=readline.createInterface({input:service.stdout});
 let app;
 try{
  const address=await Promise.race([new Promise((resolve,reject)=>{lines.once('line',line=>resolve(JSON.parse(line)));service.once('exit',code=>reject(Error('Owned OAuth service exited '+code+': '+diagnostics)));}),new Promise((_,reject)=>setTimeout(()=>reject(Error('Owned OAuth service startup timeout')),15000).unref())]);
  app=await electron.launch({executablePath:process.env.XULOOM_TEST_EXECUTABLE,args:process.env.XULOOM_TEST_EXECUTABLE?[]:[root],env,timeout:30000});
  const page=await app.firstWindow();page.setDefaultTimeout(45000);const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.locator('.project-item').click();await page.getByRole('button',{name:'MCP 市场',exact:true}).click();
  const dialog=page.getByRole('dialog',{name:'MCP 市场'});
  await page.evaluate(()=>window.xuloom.onEvent(event=>{if(event.type==='mcp_oauth_authorize')window.__ownedOAuth=event;}));
  await dialog.getByRole('button',{name:'自定义服务'}).click();
  await dialog.getByLabel('MCP 服务标识').fill('owned_oauth');await dialog.getByLabel('MCP 服务地址').fill(address.url);
  await dialog.getByLabel('MCP 认证方式').selectOption('oauth');
  await dialog.getByRole('button',{name:'保存配置',exact:true}).click();
  const card=dialog.locator('.mcp-card.installed').filter({hasText:'owned_oauth'});
  await card.getByText('未登录',{exact:true}).waitFor();
  await card.getByRole('button',{name:'测试连接',exact:true}).click();await card.getByText(/需要登录或重新授权/).waitFor();
  await card.getByRole('button',{name:'登录',exact:true}).click();
  await dialog.getByRole('button',{name:'打开授权页面'}).waitFor();
  await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
  fs.mkdirSync(path.join(root,'test-results'),{recursive:true});
  const png=await app.evaluate(async({BrowserWindow})=>(await BrowserWindow.getAllWindows()[0].webContents.capturePage(undefined,{stayHidden:true,stayAwake:true})).toPNG().toString('base64'));
  fs.writeFileSync(path.join(root,'test-results/mcp-oauth.png'),Buffer.from(png,'base64'));
  let event=await page.evaluate(()=>window.__ownedOAuth);
  const auth=await fetch(event.url,{redirect:'manual'});const callback=auth.headers.get('location');assert(callback);
  await dialog.getByText('SSH / 手动完成回调',{exact:true}).click();
  await dialog.getByLabel('OAuth 回调地址').fill(callback);await dialog.getByRole('button',{name:'提交授权回调'}).click();
  await card.getByText('已授权',{exact:true}).waitFor();
  const receipts=fs.readdirSync(path.join(data,'mcp-oauth')).filter(n=>n.endsWith('.json'));
  assert.equal(receipts.length,1);const receiptText=fs.readFileSync(path.join(data,'mcp-oauth',receipts[0]),'utf8');
  assert(!receiptText.includes('owned-access'));assert(!receiptText.includes('owned-refresh'));assert.equal(JSON.parse(receiptText).oauth_state.$xuloom_secret,'dpapi-v1');
  await card.getByRole('button',{name:'测试连接',exact:true}).click();await dialog.getByText(/连接成功，发现 0 个工具/).waitFor();
  await card.getByRole('button',{name:'重新登录',exact:true}).click();await dialog.getByRole('button',{name:'打开授权页面'}).waitFor();
  await dialog.getByRole('button',{name:'取消登录',exact:true}).click();await card.getByText('已授权',{exact:true}).waitFor();
  await card.getByRole('button',{name:'退出登录',exact:true}).click();await card.getByText('未登录',{exact:true}).waitFor();
  await card.getByRole('button',{name:'登录',exact:true}).click();await dialog.getByRole('button',{name:'打开授权页面'}).waitFor();
  await dialog.getByRole('button',{name:'取消登录',exact:true}).click();await card.getByText('未登录',{exact:true}).waitFor();
  await dialog.getByRole('button',{name:'自定义服务'}).click();
  await dialog.getByLabel('MCP 服务标识').fill('fixed_oauth');await dialog.getByLabel('MCP 服务地址').fill(address.url);
  await dialog.getByLabel('MCP 认证方式').selectOption('oauth');await dialog.getByLabel('OAuth 客户端注册').selectOption('fixed');
  await dialog.getByLabel('OAuth Client ID',{exact:true}).fill(address.fixed.client_id);
  await dialog.getByLabel('OAuth Issuer',{exact:true}).fill(address.fixed.issuer);
  await dialog.getByLabel('OAuth 注册回调地址',{exact:true}).fill(address.fixed.redirect_uri);
  await dialog.getByLabel('OAuth Client Secret',{exact:true}).fill(address.fixed.client_secret);
  const editor=dialog.locator('.mcp-editor');
  await editor.evaluate(node=>{node.scrollTop=0;});await editor.hover();await page.mouse.wheel(0,600);
  await page.waitForFunction(()=>document.querySelector('.mcp-editor')?.scrollTop>0);
  await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
  const fixedPNG=await app.evaluate(async({BrowserWindow})=>(await BrowserWindow.getAllWindows()[0].webContents.capturePage(undefined,{stayHidden:true,stayAwake:true})).toPNG().toString('base64'));
  fs.writeFileSync(path.join(root,'test-results/mcp-oauth-fixed-client.png'),Buffer.from(fixedPNG,'base64'));
  await dialog.getByRole('button',{name:'保存配置',exact:true}).click();
  const fixed=dialog.locator('.mcp-card.installed').filter({hasText:'fixed_oauth'});
  const handoff=new Promise((resolve,reject)=>lines.once('line',line=>{
    try{assert.deepEqual(JSON.parse(line),{fixed_callback_released:true});resolve();}catch(error){reject(error);}
  }));
  service.stdin.write('release-fixed\n');
  await Promise.race([handoff,new Promise((_,reject)=>setTimeout(()=>reject(Error('Callback handoff timeout')),10000).unref())]);
  await fixed.getByRole('button',{name:'登录',exact:true}).click();await dialog.getByRole('button',{name:'打开授权页面'}).waitFor();
  event=await page.evaluate(()=>window.__ownedOAuth);
  assert.equal(new URL(event.url).searchParams.get('redirect_uri'),address.fixed.redirect_uri);
  assert(!event.url.includes(address.fixed.client_secret));
  const response=await fetch(event.url,{redirect:'manual'});
  await dialog.getByText('SSH / 手动完成回调',{exact:true}).click();
  await dialog.getByLabel('OAuth 回调地址').fill(response.headers.get('location'));await dialog.getByRole('button',{name:'提交授权回调'}).click();
  await fixed.getByText('已授权',{exact:true}).waitFor();
  await fixed.getByRole('button',{name:'配置',exact:true}).click();
  assert.equal(await dialog.getByLabel('OAuth Client Secret',{exact:true}).inputValue(),'');
  assert.equal(await dialog.getByLabel('OAuth Client Secret',{exact:true}).getAttribute('placeholder'),'已保存；留空保留');
  await dialog.getByRole('button',{name:'保存配置',exact:true}).click();await fixed.getByText('已授权',{exact:true}).waitFor();
  await fixed.getByRole('button',{name:'测试连接',exact:true}).click();await dialog.getByText(/连接成功，发现 0 个工具/).waitFor();
  const settingsPath=path.join(project,'.xuloom','mcp_servers.json');
  let saved=fs.readFileSync(settingsPath,'utf8');assert(!saved.includes(address.fixed.client_secret));
  assert.equal(JSON.parse(saved).mcpServers.fixed_oauth.auth.client_secret.$xuloom_secret,'dpapi-v1');
  await fixed.getByRole('button',{name:'配置',exact:true}).click();await dialog.getByRole('button',{name:'清除已保存 Secret',exact:true}).click();
  await dialog.getByRole('button',{name:'保存配置',exact:true}).click();await fixed.getByText('未登录',{exact:true}).waitFor();
  saved=JSON.parse(fs.readFileSync(settingsPath,'utf8'));assert(!('client_secret' in saved.mcpServers.fixed_oauth.auth));
  assert.deepEqual(errors,[]);assert(!diagnostics.includes('Traceback'),diagnostics);
  console.log('PASS: hidden original/source MCP OAuth automatic and fixed-client configuration, encrypted/redacted/preserved/cleared secret, exact callback, real MCP transport, cancel/re-login, logout; no model configuration or calls');
 }catch(error){
  if(app){try{const page=(await app.windows())[0];console.error('Owned OAuth UI:',(await page.locator('body').innerText()).slice(-6000));}catch{}}
  console.error('Owned service diagnostics:',diagnostics.slice(-2000));throw error;
 }finally{
  if(app)await app.close();lines.close();service.stdin.end('stop\n');
  if(service.exitCode===null)await Promise.race([new Promise(resolve=>service.once('exit',resolve)),new Promise(resolve=>setTimeout(()=>{service.kill();resolve();},5000).unref())]);
 }
}
main().catch(e=>{console.error(e);process.exitCode=1;});
