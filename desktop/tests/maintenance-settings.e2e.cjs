const { _electron: electron } = require('playwright');
const fs = require('node:fs'), os = require('node:os'), path = require('node:path'), assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..'), fixture = fs.mkdtempSync(path.join(os.tmpdir(), 'xuloom-maintenance-ui-'));
const home = path.join(fixture, 'home'), data = path.join(fixture, 'data'), config = path.join(fixture, 'config');
for (const dir of [home, data, config]) fs.mkdirSync(dir);
const python = process.env.XULOOM_TEST_EXECUTABLE ? path.join(path.dirname(process.env.XULOOM_TEST_EXECUTABLE), 'resources/python/python.exe') : process.env.XULOOM_PYTHON || 'python';
fs.writeFileSync(path.join(data, 'workbench.json'), JSON.stringify({ projects:[], defaultDirectory:fixture, python }));
let app, page;
(async () => {
  const env = {...process.env, XULOOM_USER_DATA:path.join(fixture,'user'), XULOOM_DATA_DIR:data, XULOOM_CONFIG_DIR:config, XULOOM_TEST_HEADLESS:'1', HOME:home, USERPROFILE:home, XULOOM_PYTHON:python};
  for (const key of Object.keys(env)) if (/^(OPENAI_|ANTHROPIC_)/.test(key) || ['ELECTRON_RUN_AS_NODE','PYTHONHOME','PYTHONPATH','XULOOM_DEV_URL'].includes(key)) delete env[key];
  app = await electron.launch({executablePath:process.env.XULOOM_TEST_EXECUTABLE, args:process.env.XULOOM_TEST_EXECUTABLE ? [] : [root], env});
  page = await app.firstWindow(); page.setDefaultTimeout(45000);
  await page.waitForFunction(() => document.querySelector('.new-task')?.disabled === false);
  await page.getByRole('button',{name:'设置与模型'}).click();
  await page.getByRole('tab',{name:'备份与维护'}).click();
  const panel = page.locator('#settings-panel-maintenance');
  await panel.getByText('仅处理本机数据，不调用模型。请先停止任务。').waitFor();
  const zip = path.join(fixture, 'backup.zip');
  await app.evaluate(({dialog}, file) => { dialog.showSaveDialog = async () => ({canceled:false, filePath:file}); }, zip);
  await panel.getByRole('button',{name:'导出备份',exact:true}).click();
  await panel.getByText(/backup\.zip$/).waitFor(); assert.ok(fs.statSync(zip).size > 0);
  const diagnostic = path.join(fixture,'diagnostic.json');
  await app.evaluate(({dialog}, file) => { dialog.showSaveDialog = async () => ({canceled:false,filePath:file}); }, diagnostic);
  await panel.getByRole('button',{name:'导出诊断',exact:true}).click();
  await panel.getByText(/diagnostic\.json$/).waitFor();
  assert.equal(JSON.parse(fs.readFileSync(diagnostic)).format, 'xuloom-diagnostics-1');
  await app.evaluate(({dialog}, file) => { dialog.showOpenDialog = async () => ({canceled:false,filePaths:[file]}); }, zip);
  await panel.getByRole('button',{name:'选择备份恢复',exact:true}).click();
  await panel.getByRole('button',{name:'退出并应用'}).waitFor();
  assert.equal(await panel.getByRole('button',{name:'退出并应用'}).isDisabled(), true);
  await panel.getByRole('checkbox').check();
  assert.equal(await panel.getByRole('button',{name:'退出并应用'}).isEnabled(), true);
  const png = await app.evaluate(async ({BrowserWindow}) => (await BrowserWindow.getAllWindows()[0].webContents.capturePage(undefined,{stayHidden:true,stayAwake:true})).toPNG().toString('base64'));
  fs.mkdirSync(path.join(root,'test-results'),{recursive:true});fs.writeFileSync(path.join(root,'test-results/maintenance-settings.png'),Buffer.from(png,'base64'));
  console.log('Maintenance settings E2E passed: backup, diagnostics, restore preview and confirmation; no model calls.');
})().catch(async e => {console.error(e); if(page) console.error(await page.locator('body').innerText());process.exitCode=1;}).finally(async () => {if(app)await app.close();fs.rmSync(fixture,{recursive:true,force:true});});
