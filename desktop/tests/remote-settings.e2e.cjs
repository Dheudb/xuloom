const { _electron: electron } = require('playwright');
const fs = require('node:fs'), path = require('node:path'), os = require('node:os'), assert = require('node:assert/strict');
const { spawnSync } = require('node:child_process');
const { resolveEnginePython } = require('../electron/runtime.cjs');
const root = path.resolve(__dirname, '..'), fixture = fs.mkdtempSync(path.join(os.tmpdir(), 'xuloom-ssh-settings-'));
const config = path.join(fixture, 'config'), data = path.join(fixture, 'data'), home = path.join(fixture, 'home');
for (const directory of [config, data, home]) fs.mkdirSync(directory);
fs.writeFileSync(path.join(config, 'config.json'), JSON.stringify({model_connections: []}));
const env = {...process.env, XULOOM_CONFIG_DIR: config, XULOOM_DATA_DIR: data, XULOOM_USER_DATA: data, HOME: home, USERPROFILE: home, XULOOM_TEST_HEADLESS: '1', XULOOM_SKILLS_PATHS: ''};
for (const key of ['ELECTRON_RUN_AS_NODE', 'XULOOM_DEV_URL', 'OPENAI_API_KEY', 'OPENAI_MODEL', 'OPENAI_BASE_URL', 'XULOOM_MODEL_PROVIDER']) delete env[key];
let app, page;
(async () => { try {
 app = await electron.launch({executablePath: process.env.XULOOM_TEST_EXECUTABLE, args: process.env.XULOOM_TEST_EXECUTABLE ? [] : [root], env});
 page = await app.firstWindow(); page.setDefaultTimeout(30000);
 await page.getByRole('button', {name: '设置与模型', exact: true}).click();
 await page.getByRole('tab', {name: 'SSH 远程', exact: true}).click();
 await page.getByRole('button', {name: '新增 SSH 连接', exact: true}).click();
 await page.getByLabel('SSH 连接 ID', {exact: true}).fill('local-test');
 await page.getByLabel('SSH 连接名称', {exact: true}).fill('测试连接');
 await page.getByLabel('SSH 主机', {exact: true}).fill('127.0.0.1');
 await page.getByLabel('SSH 远端目录', {exact: true}).fill('/home/test/project');
 await page.locator('.remote-settings summary').click();
 await page.getByLabel('SSH 端口', {exact: true}).fill('1');
 await page.getByRole('button', {name: '保存 SSH 连接', exact: true}).click();
 await page.getByRole('status').filter({hasText: 'SSH 连接已保存'}).waitFor();
 const saved = JSON.parse(fs.readFileSync(path.join(config, 'config.json'), 'utf8')).ssh_connections[0];
 assert.equal(saved.id, 'local-test'); assert.equal(saved.host, '127.0.0.1'); assert.equal(saved.port, 1);
 assert(!('api_key' in saved)); assert(!('password' in saved));
 const installed = process.env.XULOOM_TEST_EXECUTABLE;
 const python = installed ? path.join(path.dirname(installed), 'resources', 'python', 'python.exe') : resolveEnginePython({packaged: false, projectRoot: path.resolve(root, '..')});
 const cli = spawnSync(python, ['-I', '-m', 'xuloom', 'remote', 'list', '--json'], {env, encoding: 'utf8', timeout: 30000});
 assert.equal(cli.status, 0, cli.stderr); assert.equal(JSON.parse(cli.stdout.trim()).result.connections[0].id, 'local-test');
 await page.getByRole('button', {name: '测试 SSH 连接', exact: true}).click();
 await page.getByRole('alert').filter({hasText: 'SSH connection ended'}).waitFor({timeout: 45000});
 await page.getByRole('button', {name: '删除连接配置', exact: true}).click();
 await page.getByRole('status').filter({hasText: 'SSH 连接配置已删除'}).waitFor();
 assert.deepEqual(JSON.parse(fs.readFileSync(path.join(config, 'config.json'), 'utf8')).ssh_connections, []);
 console.log('Remote settings E2E passed: keyless profile CRUD, shared formal CLI, strict connection failure, no local model required');
 } finally { if (app) await app.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
