"""Conservative distribution omissions; never remove runtime binaries or licenses."""
import hashlib
from pathlib import Path, PurePosixPath

SITE = 'resources/python/Lib/site-packages/'
DEVELOPMENT = (
    'pymupdf/mupdf-devel/', 'win32/include/', 'win32/libs/',
    'win32com/include/', 'win32com/libs/', 'win32com/HTML/',
    'win32/test/', 'win32/Demos/', 'win32com/test/', 'win32com/demos/',
    'adodbapi/test/', 'adodbapi/examples/', 'isapi/test/', 'isapi/samples/', 'isapi/doc/',
    'jsonschema/tests/', 'jsonschema_specifications/tests/', 'referencing/tests/',
    'gitdb/test/', 'smmap/test/', 'certifi/tests/',
)
COM_DEVELOPMENT = ('adsi/demos/', 'axscript/demos/', 'axscript/test/', 'authorization/demos/',
    'bits/test/', 'directsound/test/', 'ifilter/demos/', 'mapi/demos/', 'propsys/test/',
    'shell/demos/', 'shell/test/', 'taskscheduler/test/')


def omitted_reason(relative):
    """Exact known development paths, not a blanket tests/docs filename filter."""
    path = PurePosixPath(relative)
    if path.is_absolute() or '..' in path.parts or '\\' in str(relative):
        raise ValueError('Invalid distribution-relative path')
    name = path.name.lower()
    if any(word in name for word in ('license', 'copying', 'copyright', 'notice')):
        return None
    if path.suffix.lower() in {'.dll', '.pyd', '.exe', '.so', '.dylib', '.pak', '.pem', '.crt', '.cer', '.der', '.pfx', '.p12', '.ttf', '.otf', '.woff', '.woff2'}:
        return None
    value = path.as_posix()
    if not value.startswith('resources/python/Lib/'):
        return None
    if '__pycache__' in path.parts and path.suffix == '.pyc':
        return 'generated bytecode cache'
    if not value.startswith(SITE):
        return None
    package = value[len(SITE):]
    if (package == 'PyWin32.chm' or package.startswith(DEVELOPMENT)
            or package.startswith(tuple('win32comext/' + item for item in COM_DEVELOPMENT))):
        return 'dependency development files'
    return None


def retirements(package, replaced=()):
    """Hash only explicit omissions outside resources replaced by this update."""
    root = Path(package).resolve()
    replaced = tuple(PurePosixPath(name) for name in replaced)
    items = []
    for path in root.rglob('*'):
        if path.is_symlink() or getattr(path.lstat(), 'st_file_attributes', 0) & 0x400:
            raise ValueError('Refusing linked package resources')
        if not path.is_file():
            continue
        relative = PurePosixPath(path.relative_to(root).as_posix())
        if any(relative == parent or parent in relative.parents for parent in replaced):
            continue
        reason = omitted_reason(relative)
        # Existing caches keep warm-start behavior and may change while staging.
        # They are already excluded from new archives; do not retire them here.
        if reason and reason != 'generated bytecode cache':
            items.append({'path': relative.as_posix(), 'sha256': hashlib.sha256(path.read_bytes()).hexdigest(),
                          'bytes': path.stat().st_size, 'reason': reason})
    return sorted(items, key=lambda item: item['path'])


def prune_generated_runtime(runtime):
    """Used only on a fresh generated runtime, before it becomes an installation."""
    root = Path(runtime).resolve()
    removed = []
    for path in root.rglob('*'):
        if path.is_symlink() or getattr(path.lstat(), 'st_file_attributes', 0) & 0x400:
            raise ValueError('Refusing linked runtime resources')
        if path.is_file() and omitted_reason('resources/python/' + path.relative_to(root).as_posix()):
            if not path.resolve().is_relative_to(root):
                raise ValueError('Runtime resource escaped generated directory')
            removed.append({'path': path.relative_to(root).as_posix(), 'bytes': path.stat().st_size})
            path.unlink()
    return removed
