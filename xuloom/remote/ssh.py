"""Thin JSONL RPC over system OpenSSH, with no credential transfer or replay."""
import asyncio
import base64
import json
import os
import shlex
import shutil

from xuloom.remote.config import validate_profile

PROTOCOL_VERSION = 1
MAX_LINE = 64 * 1024 * 1024


class RemoteDisconnected(ConnectionError):
    """Connection loss is not proof that remote effects stopped or failed."""


class RemoteRequestError(ValueError):
    def __init__(self, message, code="error"):
        super().__init__(message)
        self.code = code if code in {"session_busy", "session_conflict", "persistence_error", "invalid_request"} else "error"


def command(profile, *, worker=False):
    profile = validate_profile(profile)
    if type(worker) is not bool:
        raise ValueError("Invalid SSH execution endpoint")
    # The payload is code generated by this client. User strings are JSON
    # literals inside it, then base64 encoded, never interpolated shell code.
    module = "xuloom.remote.worker_bridge" if worker else "xuloom.desktop.bridge"
    code = "import os,runpy;os.chdir(" + repr(profile["cwd"]) + ");os.environ['XULOOM_REMOTE']='1';runpy.run_module(" + repr(module) + ",run_name='__main__')"
    encoded = base64.b64encode(code.encode("utf-8")).decode("ascii")
    bootstrap = "import base64;exec(base64.b64decode('" + encoded + "'))"
    argv = [profile["python"], "-I", "-u", "-c", bootstrap]
    if profile["platform"] == "windows":
        script = "& " + " ".join("'" + part.replace("'", "''") + "'" for part in argv) + "; exit $LASTEXITCODE"
        return "powershell.exe -NoLogo -NoProfile -NonInteractive -EncodedCommand " + base64.b64encode(script.encode("utf-16le")).decode("ascii")
    return shlex.join(argv)


def ssh_argv(profile, *, worker=False):
    profile = validate_profile(profile)
    executable = shutil.which("ssh")
    if not executable:
        raise ValueError("OpenSSH client is not installed or is not on PATH")
    argv = [executable, "-T", "-o", "BatchMode=yes", "-o", "StrictHostKeyChecking=yes",
        "-o", "ConnectTimeout=10", "-o", "ServerAliveInterval=15", "-o", "ServerAliveCountMax=3",
        "-o", "ForwardAgent=no", "-o", "ForwardX11=no", "-o", "ClearAllForwardings=yes", "-o", "ControlMaster=no", "-o", "ControlPath=none"]
    if profile["ssh_config"]: argv += ["-F", os.path.expanduser(profile["ssh_config"])]
    if profile["port"] is not None: argv += ["-p", str(profile["port"])]
    return argv + ["--", profile["host"], command(profile, worker=worker)]


class SSHClient:
    def __init__(self, profile, on_event=None, *, worker=False):
        self.profile = validate_profile(profile)
        if type(worker) is not bool:
            raise ValueError("Invalid SSH execution endpoint")
        self.worker = worker
        self.on_event = on_event or (lambda event: None)
        self.sequence, self.pending = 0, {}
        self.process = None
        self.reader_task = self.stderr_task = None
        self.closed = False
        self.closing = False
        self.stderr = ""
        self.info = None

    async def start(self):
        if self.process is not None: raise RuntimeError("SSH client has already started")
        options = {"creationflags": 0x08000000} if os.name == "nt" else {}
        environment = {key: value for key, value in os.environ.items() if not key.startswith(("OPENAI_", "ANTHROPIC_", "XULOOM_"))}
        self.process = await asyncio.create_subprocess_exec(*ssh_argv(self.profile, worker=self.worker), stdin=asyncio.subprocess.PIPE,
            stdout=asyncio.subprocess.PIPE, stderr=asyncio.subprocess.PIPE, limit=MAX_LINE, env=environment, **options)
        self.stderr_task = asyncio.create_task(self._stderr())
        self.reader_task = asyncio.create_task(self._read())
        try:
            self.info = await self.request("runtime.info", timeout=30)
            if not isinstance(self.info, dict) or self.info.get("protocol") != PROTOCOL_VERSION:
                raise ValueError("Remote Xuloom protocol is incompatible; update the remote installation")
            return self.info
        except BaseException:
            await self.aclose(graceful=False)
            raise

    async def _stderr(self):
        while chunk := await self.process.stderr.read(4096):
            self.stderr = (self.stderr + chunk.decode("utf-8", "replace"))[-6000:]

    async def _read(self):
        error = None
        try:
            while line := await self.process.stdout.readline():
                try: message = json.loads(line.decode("utf-8"))
                except (ValueError, UnicodeError): raise RemoteDisconnected("Remote stdout is not Xuloom JSONL; remove shell banners or update the remote installation") from None
                if not isinstance(message, dict): raise RemoteDisconnected("Invalid remote protocol message")
                if "event" in message:
                    if not isinstance(message["event"], dict): raise RemoteDisconnected("Invalid remote event")
                    self.on_event({**message["event"], "remote": {"id": self.profile["id"], "host": self.profile["host"]}})
                    continue
                future = self.pending.pop(message.get("id"), None)
                if future is not None and not future.done():
                    if "error" in message: future.set_exception(RemoteRequestError(str(message["error"]), message.get("errorCode")))
                    elif "result" in message: future.set_result(message["result"])
                    else: future.set_exception(RemoteDisconnected("Incomplete remote response"))
        except BaseException as exc:
            error = exc
        finally:
            self.closed = True
            if error is None:
                await self.process.wait()
                if self.stderr_task: await self.stderr_task
                error = RemoteDisconnected("SSH connection ended; remote outcome is unconfirmed. " + self.stderr)
            for future in self.pending.values():
                if not future.done(): future.set_exception(error)
            self.pending.clear()
            if not self.closing:
                self.on_event({"type": "remote_disconnected", "message": str(error),
                    "remote": {"id": self.profile["id"], "host": self.profile["host"]}, "outcome_unknown": True})

    async def request(self, method, params=None, *, timeout=60):
        if self.process is None or self.closed: raise RemoteDisconnected("SSH connection is not open")
        self.sequence += 1
        identity = self.sequence
        future = asyncio.get_running_loop().create_future()
        self.pending[identity] = future
        try:
            self.process.stdin.write((json.dumps({"id": identity, "method": method, "params": params or {}}, ensure_ascii=False) + "\n").encode("utf-8"))
            await self.process.stdin.drain()
            return await asyncio.wait_for(future, timeout)
        except (BrokenPipeError, ConnectionResetError):
            raise RemoteDisconnected("SSH write failed; remote outcome is unconfirmed") from None
        except asyncio.TimeoutError:
            # Never resend this RPC automatically. Its effect may have occurred.
            raise RemoteDisconnected("Remote request timed out; outcome is unconfirmed: " + method) from None
        finally:
            self.pending.pop(identity, None)

    async def aclose(self, *, graceful=True):
        if self.process is None: return
        self.closing = True
        error = None
        if graceful and not self.closed:
            try: await self.request("shutdown", timeout=20)
            except (ConnectionError, ValueError, OSError) as exc: error = exc
        if not self.process.stdin.is_closing(): self.process.stdin.close()
        try: await asyncio.wait_for(self.process.wait(), 5)
        except asyncio.TimeoutError:
            # Only our SSH subprocess; never kill an arbitrary remote PID.
            self.process.terminate()
            try: await asyncio.wait_for(self.process.wait(), 5)
            except asyncio.TimeoutError: self.process.kill(); await self.process.wait()
        await asyncio.gather(*(task for task in (self.reader_task, self.stderr_task) if task is not None), return_exceptions=True)
        self.closed = True
        if error: raise error
